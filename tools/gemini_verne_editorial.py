#!/usr/bin/env python3
"""Resumable, source-grounded Gemini chapter editorial drafts for Verne (staging only).

Every output is an independently hashed, recoverable batch. Nothing generated by
the model is imported into the APK, accepted as a finished translation, or
presented as verified rights clearance. No generated literature; only existing
original English paragraphs are supplied from the checked-in Towle edition.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import time
from urllib import error, request

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs/literature/staging/gemini-verne-editorial"
BASE_API = "https://generativelanguage.googleapis.com/v1beta"
CHAPTER_COUNT = 37
PARAGRAPHS_PER_SEGMENT = 8
DEFAULT_MAX_SEGMENTS = 4
MAX_RESPONSE_BYTES = 900_000
MODEL_PREFERENCES = (
    # New AI Studio projects often cannot generate with 2.5 despite models.list.
    "gemini-3.5-flash-lite", "gemini-3.5-flash", "gemini-3.1-flash-lite",
    "gemini-3.6-flash", "gemini-3.7-flash", "gemini-3.8-flash",
    "gemini-2.5-flash", "gemini-2.5-flash-lite",
)


def digest(value: object) -> str:
    packed = json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(packed.encode("utf-8")).hexdigest()


def atomic_write(path: Path, data: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    temporary.replace(path)


def chapter_source(number: int) -> dict:
    cp = subprocess.run(
        ["node", str(ROOT / "tools/export_verne_chapter.cjs"), str(number)],
        capture_output=True, text=True, check=True, timeout=40,
    )
    source = json.loads(cp.stdout)
    if source["chapterOneBased"] != number or source["workId"] != "around-the-world-in-eighty-days-towle":
        raise ValueError("Unexpected or mismatched original work")
    indices = [p["index"] for p in source["paragraphs"]]
    if indices != list(range(len(indices))):
        raise ValueError("Original chapter contains missing or duplicate paragraph indices")
    return source


def segment_path(chapter: int, start: int) -> Path:
    return OUTPUT / f"chapter-{chapter:02d}" / f"paragraphs-{start:04d}-{start + PARAGRAPHS_PER_SEGMENT - 1:04d}.json"


def read_existing(path: Path, checksum: str) -> dict | None:
    if not path.exists():
        return None
    record = json.loads(path.read_text(encoding="utf-8"))
    if record.get("sourceSha256") != checksum:
        raise ValueError("Original text changed since the stored batch; refusing overwrite: " + str(path))
    if record.get("status") not in ("AI_DRAFT_REVIEW_PENDING", "AI_DRAFT_REVIEWED_NOT_APPROVED"):
        raise ValueError("Unexpected existing checkpoint status: " + str(path))
    return record


def validate_entries(data: dict, field: str, count: int) -> list[dict]:
    entries = data.get(field)
    if not isinstance(entries, list) or len(entries) != count:
        raise ValueError("Gemini response has an incomplete " + field + " array")
    indices = [e.get("index") for e in entries if isinstance(e, dict)]
    if len(indices) != count or any(type(i) is not int for i in indices) or sorted(indices) != list(range(count)):
        raise ValueError("Gemini returned missing/duplicate or invalid paragraph indices")
    if field == "translations":
        for e in entries:
            ar = e.get("ar")
            if not isinstance(ar, str) or len(ar.strip()) < 3 or not re.search(r"[\u0600-\u06FF]", ar):
                raise ValueError("Gemini returned empty or non-Arabic paragraph")
    else:
        for e in entries:
            if type(e.get("adequate")) is not bool or not isinstance(e.get("issues"), str):
                raise ValueError("Gemini returned an invalid review record")
    return sorted(entries, key=lambda e: e["index"])


def http_json(url: str, key: str, payload: dict | None = None) -> dict:
    body = json.dumps(payload, ensure_ascii=False).encode("utf-8") if payload is not None else None
    headers = {"x-goog-api-key": key, "Accept": "application/json"}
    if body is not None:
        headers["Content-Type"] = "application/json"
    for attempt in range(4):
        try:
            with request.urlopen(request.Request(url, data=body, headers=headers, method="POST" if body else "GET"),
                                 timeout=95) as response:
                raw = response.read(MAX_RESPONSE_BYTES + 1)
                if len(raw) > MAX_RESPONSE_BYTES:
                    raise ValueError("Gemini response exceeded maximum allowed size")
                return json.loads(raw)
        except error.HTTPError as exc:
            # Never dump response body: providers may echo sensitive request data.
            if exc.code in (429, 500, 502, 503, 504) and attempt < 3:
                retry_after = exc.headers.get("Retry-After", "")
                pause = min(60, int(retry_after)) if retry_after.isdigit() else min(60, 5 * 2 ** attempt)
                print(f"Gemini HTTP {exc.code}; retrying after {pause}s", flush=True)
                time.sleep(pause)
                continue
            raise RuntimeError(f"Gemini request rejected: HTTP {exc.code}") from None
        except (error.URLError, TimeoutError):
            if attempt < 3:
                time.sleep(5 * (attempt + 1))
                continue
            raise RuntimeError("Gemini API network failure after retries") from None
    raise RuntimeError("Gemini retries exhausted")


def choose_models(key: str) -> list[str]:
    models = http_json(BASE_API + "/models", key).get("models", [])
    available = {
        m.get("name", "").removeprefix("models/") for m in models
        if "generateContent" in m.get("supportedGenerationMethods", [])
    }
    user_choice = os.environ.get("GEMINI_MODEL", "").strip()
    ordered = ([user_choice] if user_choice else []) + list(MODEL_PREFERENCES)
    # Discover future supported Flash text models without guessing names.
    ordered += sorted(
        (m for m in available if re.match(r"^gemini-[0-9.]+-flash(?:-lite)?$", m)),
        reverse=True,
    )
    choices = list(dict.fromkeys(m for m in ordered if m in available))
    if not choices:
        raise RuntimeError("No supported Gemini text-generation models returned for this key")
    print("Discovered", len(choices), "allowed Gemini text models; first:", choices[0], flush=True)
    return choices


def output_schema(task: dict) -> dict:
    field = next(iter(task["outputStrictJSON"]))
    count = len(task["paragraphs"])
    if field == "translations":
        props = {"index": {"type": "integer"}, "ar": {"type": "string"}}
        required = ["index", "ar"]
    elif field == "checks":
        props = {"index": {"type": "integer"}, "adequate": {"type": "boolean"},
                 "issues": {"type": "string"}}
        required = ["index", "adequate", "issues"]
    else:
        raise ValueError("Unknown output schema type")
    return {
        "type": "object",
        "properties": {
            field: {
                "type": "array", "minItems": count, "maxItems": count,
                "items": {"type": "object", "properties": props, "required": required},
            },
        },
        "required": [field],
    }


def generate(key: str, model: str, task: dict) -> dict:
    result = http_json(
        BASE_API + "/models/" + model + ":generateContent", key,
        {"contents": [{"role": "user", "parts": [{"text": json.dumps(task, ensure_ascii=False)}]}],
         "generationConfig": {
             "temperature": 0.1,
             "responseMimeType": "application/json",
             "responseJsonSchema": output_schema(task),
             "maxOutputTokens": 8192,
         }},
    )
    try:
        reply = "".join(p["text"] for p in result["candidates"][0]["content"]["parts"] if "text" in p)
        parsed = json.loads(reply)
        expected = next(iter(task["outputStrictJSON"]))
        validate_entries(parsed, expected, len(task["paragraphs"]))
        return parsed
    except (KeyError, IndexError, ValueError, TypeError) as exc:
        raise ValueError("Gemini structured result was incomplete or violated paragraph count") from exc


def translate_task(rows: list[dict], chapter: int) -> dict:
    return {
        "role": "Arabic literary editorial assistant reviewing a public-domain historical novel",
        "goal": "Produce a faithful full Arabic translation revision for EACH original English paragraph, preserving every character's name, dialogue, events, nuance and paragraph order. Existing Arabic is a draft only. Do not summarize, omit, extend, invent, or censor. Keep first-person and narrative perspectives. Ensure context-sensitive natural literary Arabic.",
        "outputStrictJSON": {"translations": [{"index": 0, "ar": "full paragraph Arabic"}]},
        "chapter": chapter,
        "paragraphs": [{"index": i, "originalEnglish": p["en"], "existingArabicDraft": p["existingArabicDraft"]}
                       for i, p in enumerate(rows)],
    }


def review_task(rows: list[dict], revisions: list[dict], chapter: int) -> dict:
    return {
        "role": "Independent bilingual quality reviewer; do not approve publication",
        "goal": "For EACH index, compare revised Arabic to original English; flag omitted information, invented content, incorrect historical nuance, dialogue, names or mistranslation. 'adequate' should be false if issues are identified. Return concise issues in Arabic. Do not claim copyright review.",
        "outputStrictJSON": {"checks": [{"index": 0, "adequate": True, "issues": ""}]},
        "chapter": chapter,
        "paragraphs": [{"index": i, "originalEnglish": p["en"], "revisedArabic": revisions[i]["ar"]}
                       for i, p in enumerate(rows)],
    }


def run(max_segments: int) -> int:
    key = os.environ.get("GEMINI_API_KEY", "").strip()
    if not key:
        raise RuntimeError("GEMINI_API_KEY Actions secret is missing")
    models = choose_models(key)
    model = models[0]

    def guarded_generate(task: dict) -> dict:
        nonlocal model
        while True:
            try:
                return generate(key, model, task)
            except RuntimeError as exc:
                if not any(("HTTP " + code) in str(exc) for code in ("404", "503")):
                    raise
                idx = models.index(model)
                if idx + 1 >= len(models):
                    raise RuntimeError("All supported Gemini models refused generation (404 or 503)") from None
                model = models[idx + 1]
                print("Model unavailable for generation (404/503); trying fallback:", model, flush=True)

    produced = 0
    for ch in range(1, CHAPTER_COUNT + 1):
        source = chapter_source(ch)
        paragraphs = source["paragraphs"]
        for start in range(0, len(paragraphs), PARAGRAPHS_PER_SEGMENT):
            rows = paragraphs[start:start + PARAGRAPHS_PER_SEGMENT]
            checksum = digest({"workId": source["workId"], "chapter": ch, "rows": rows})
            path = segment_path(ch, start)
            existing = read_existing(path, checksum)
            if existing is not None and existing["status"] == "AI_DRAFT_REVIEWED_NOT_APPROVED":
                continue
            record = existing or {
                "status": "AI_DRAFT_REVIEW_PENDING",
                "publicationStatus": "STAGING_ONLY_NOT_IN_APK",
                "humanEditorialAcceptance": False,
                "territorialRightsClearance": False,
                "bookId": source["workId"],
                "chapterOneBased": ch,
                "chapterTitle": source["chapterTitle"],
                "startParagraphZeroBased": start,
                "paragraphCount": len(rows),
                "sourceSha256": checksum,
                "sourceFileShas256": source["sourceFileShas256"],
                "sourceEdition": "Jules Verne, George Makepeace Towle 1873 English translation",
                "originalTextAndDraft": rows,
            }
            if "proposedArabic" not in record:
                proposal = guarded_generate(translate_task(rows, ch))
                record["proposedArabic"] = validate_entries(proposal, "translations", len(rows))
                record["model"] = model
                atomic_write(path, record)  # keep draft even if independent review fails
                print("SAVED provisional chapter", ch, "paragraphs", start, "to", start + len(rows) - 1, flush=True)
            review = guarded_generate(review_task(rows, record["proposedArabic"], ch))
            record["independentAiChecks"] = validate_entries(review, "checks", len(rows))
            record["status"] = "AI_DRAFT_REVIEWED_NOT_APPROVED"
            record["autoPublishAllowed"] = False
            record["needsHumanReview"] = True
            atomic_write(path, record)
            produced += 1
            print("REVIEWED provisional chapter", ch, "segment", start // PARAGRAPHS_PER_SEGMENT + 1, flush=True)
            if produced >= max_segments:
                return produced
    return produced


def self_test() -> None:
    rows = [{"en": "The time had come.", "existingArabicDraft": "حان الوقت."}]
    payload = translate_task(rows, 1)
    assert payload["paragraphs"][0]["index"] == 0
    assert output_schema(payload)["properties"]["translations"]["minItems"] == 1
    assert len(validate_entries({"translations": [{"index": 0, "ar": "لقد حان الوقت."}]}, "translations", 1)) == 1
    assert len(validate_entries({"checks": [{"index": 0, "adequate": True, "issues": ""}]}, "checks", 1)) == 1
    for invalid in ({"translations": []}, {"translations": [{"index": 0, "ar": "English only"}]},
                    {"translations": [{"index": 2, "ar": "اختبار"}]}):
        try:
            validate_entries(invalid, "translations", 1)
        except ValueError:
            pass
        else:
            raise AssertionError("Invalid model output was accepted")
    print("PASS: Gemini editorial batch validation self-test")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--max-segments", type=int, default=DEFAULT_MAX_SEGMENTS)
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    if args.self_test:
        self_test()
    elif not 1 <= args.max_segments <= 12:
        parser.error("--max-segments must be between 1 and 12")
    else:
        try:
            completed = run(args.max_segments)
            print(f"AI editorial segments reviewed in this run: {completed}; complete new books: 0; published: 0")
        except Exception as exc:
            # Prevent traceback or URL/headers containing the secret from entering Actions logs.
            message = str(exc)
            secret = os.environ.get("GEMINI_API_KEY", "")
            if secret:
                message = message.replace(secret, "[REDACTED]")
            print("Gemini editorial run interrupted; previous checkpoints retained:", message, file=sys.stderr)
            sys.exit(1)
