#!/usr/bin/env python3
"""Independent StoryLens CI failure triage: prints exact missing modules and fixtures.
Read-only; does not mutate APK or source. Run: python3 tools/ci_triage.py
"""
from pathlib import Path
import re
import sys
import zipfile

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "app/src/main/assets"
WORKFLOW = ROOT / ".github/workflows/android.yml"
text = WORKFLOW.read_text(encoding="utf-8")
required = re.findall(r'for file in ([^\n]+); do', text)
required = required[-1].split() if required else []
errors = []
print("StoryLens CI asset diagnostics")
for filename in required:
    found = (ASSETS / filename).is_file()
    print(("OK " if found else "MISSING ") + "assets/" + filename)
    if not found:
        errors.append("Missing source asset: " + filename)
for script in ("tools/make_browser_fixtures.py", "tools/test_freedict.py", "tools/build_freedict.py"):
    if not (ROOT / script).is_file():
        errors.append("Missing workflow helper: " + script)
for file in ("qa-reader.html", "qa-word.html", "qa-flow.html"):
    if (ASSETS / file).exists():
        print("PRESENT fixture: " + file)
    else:
        print("DYNAMIC fixture (must be generated by make_browser_fixtures.py): " + file)
apks = list((ROOT / "app/build/outputs/apk/debug").glob("*.apk"))
if apks:
    with zipfile.ZipFile(apks[0]) as archive:
        members = set(archive.namelist())
        for filename in required:
            if "assets/" + filename not in members:
                errors.append("APK missing: assets/" + filename)
else:
    print("APK unavailable locally; packaging check deferred to GitHub Actions")
if errors:
    print("\nFAIL:")
    for error in errors:
        print(" - " + error)
    sys.exit(1)
print("\nPASS: required source files exist; APK check " + ("passed" if apks else "pending"))
