'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const wf = fs.readFileSync('.github/workflows/android.yml', 'utf8');
const build = fs.readFileSync('app/build.gradle.kts', 'utf8');
assert.match(wf, /gradle --no-daemon :app:testDebugUnitTest :app:assembleDebug :app:assembleRelease/, 'Build release even with no key');
assert.match(wf, /- name: Verify unsigned production APK for offline personal signing/, 'Unsigned release must be verified before packaging');
assert.match(wf, /name='com\.storylens\.reader'/, 'Production package not preview');
assert.match(wf, /test "\$code" = "\$\(\(100000 \+ GITHUB_RUN_NUMBER\)\)"/, 'Unsigned release must have monotonic CI versionCode');
assert.match(wf, /if "\$APKSIGNER" verify "\$RELEASE" >/,'Reject any ambiguously signed unsigned artifact');
assert.match(wf, /variant=unsigned-production/, 'Explicit unsigned metadata distinguishes it from signed release');
assert.match(wf, /artifact_is_NOT_installable=TRUE/, 'Never advertise unsigned output as installable');
assert.match(wf, /for asset in index\.html reader-experience\.js/, 'Verify real tested files are byte-identical');
assert.match(wf, /test "\$\(unzip -p "\$DEBUG"/, 'Verify packaged SHA rather than source only');
assert.match(wf, /cp "\$ANDROID_HOME\/build-tools\/36\.0\.0\/lib\/apksigner\.jar"/, 'Offline owner signer obtains official Android jar');
assert.match(wf, /name: Lingua-Tales-Unsigned-Production-NOT-INSTALLABLE/, 'Unsigned product artifact has unmistakable name');
assert.match(wf, /if: success\(\) && env\.LT_SIGNING_KEYSTORE == ''/, 'Unsigned artifact only when GitHub secrets are absent');
assert.match(build, /applicationId = "com\.storylens\.reader"/, 'Production identity stays constant');
assert.match(build, /versionName = "1\.0\.0"/, 'Stable first-install visible version');
console.log('PASS: no-key unsigned production build, package/version/content gates and official signing utility artifact');
