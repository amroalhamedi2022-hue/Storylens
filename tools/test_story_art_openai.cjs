#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict');
const {buildRequest,parseArgs,parseResult,signature,inside,digest}=require('./generate_story_art_openai.cjs');
const {run}=require('./story_art_pilot.cjs');
const original=run(['--check']).queue[0];
assert.equal(parseArgs(['--scene',original.sceneId]).execute,false);
assert.throws(()=>parseArgs(['--scene',original.sceneId,'--execute']),/BOTH/);
assert.throws(()=>parseArgs(['--scene',original.sceneId,'--confirm-paid']),/BOTH/);
assert.throws(()=>parseArgs(['--scene','../wrong']),/Select one real/);
const standard=buildRequest(original,'gpt-image-2.6-flare',[]);
assert.equal(standard.endpoint,'/v1/images/generations');
assert.equal(standard.body.n,1);
assert.equal(standard.body.output_format,'webp');
assert.equal(standard.body.model,'gpt-image-2.6-flare');
assert.ok(!('images' in standard.body));
const one=Buffer.concat([Buffer.from('RIFF'),Buffer.alloc(4),Buffer.from('WEBP'),Buffer.alloc(512)]);
const mime=signature(one,'.webp');
assert.equal(mime,'image/webp');
const edit=buildRequest(original,'gpt-image-2.6-sunburst',[{mime,data:one,hash:digest(one)}]);
assert.equal(edit.endpoint,'/v1/images/edits');
assert.equal(edit.body.images.length,1);
assert.ok(edit.body.images[0].image_url.startsWith('data:image/webp;base64,'));
assert.ok(!('images' in standard.body),'text-only never includes references');
assert.equal(parseResult({data:[{b64_json:one.toString('base64')}]}).length,one.length);
assert.throws(()=>parseResult({data:[{b64_json:'notimage'}]}));
assert.throws(()=>buildRequest(original,'unsupported-model',[]),/approved/);
assert.throws(()=>buildRequest({...original,status:'PUBLISHED'},'gpt-image-2.6-flare',[]));
assert.equal(inside('/tmp/reference','/tmp/reference/cover.webp'),true);
assert.equal(inside('/tmp/reference','/tmp/escape.webp'),false);
const {run:colorRun}=require('./prepare_color_scene_queue.cjs');
const colored=colorRun(['--check']);
assert.equal(colored.queueCount,6);
const ch3=colored.queue.find(x=>x.chapterOneBased===3);
assert.ok(ch3&&ch3.sceneId==='verne-ch03-color-wager');
assert.equal(parseArgs(['--color-scenes','--scene',ch3.sceneId]).execute,false);
assert.equal(parseArgs(['--color-scenes','--scene',ch3.sceneId]).colorScenes,true);
assert.throws(()=>parseArgs(['--scene',ch3.sceneId]),/Select one real/);
assert.throws(()=>parseArgs(['--color-scenes','--scene',ch3.sceneId,'--execute']),/BOTH/);
assert.equal(buildRequest(ch3,'gpt-image-2.6-flare',[]).endpoint,'/v1/images/generations');
assert.ok(ch3.prompt.includes('SINGLE-FRAME')&&ch3.sourceParagraphSha256.length===64);
const {verified:productionVerified}=require('./story_art_queue_60.cjs');
const production=productionVerified();
const chapter5=production.colorMap.get('verne-ch05-color-telegram-arrives');
if(chapter5){
 assert.equal(chapter5.chapterOneBased,5);
 assert.equal(chapter5.afterParagraph,8);
 assert.ok(chapter5.prompt.includes('commissioner of police'));
 assert.equal(parseArgs(['--queue-scenes','--scene',chapter5.sceneId]).queueScenes,true);
 assert.equal(parseArgs(['--queue-scenes','--scene',chapter5.sceneId]).execute,false);
 assert.throws(()=>parseArgs(['--color-scenes','--queue-scenes','--scene',chapter5.sceneId]),/one scene queue/);
 assert.throws(()=>parseArgs(['--queue-scenes','--scene',chapter5.sceneId,'--execute']),/BOTH/);
 assert.equal(buildRequest(chapter5,'gpt-image-2.6-flare',[]).endpoint,'/v1/images/generations');
}
console.log('PASS: one-scene paid-call opt-in, real source-only queue, API generation/reference payload, WebP bytes, no overwrite contract');
