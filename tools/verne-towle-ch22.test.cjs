'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const assets=path.join(root,'app/src/main/assets');
const read=n=>fs.readFileSync(path.join(assets,n),'utf8');
const file=read('classic-verne-towle-ch22.js');
const html=read('index.html');
assert.ok(html.includes('src="classic-verne-towle-ch21.js"'));
assert.ok(html.includes('src="classic-verne-towle-ch22.js"'));
assert.ok(html.includes('src="classic-verne-towle-ch23.js"'));
assert.ok(html.indexOf('classic-verne-towle-ch22.js')<html.indexOf('classic-verne-towle-ch23.js'));
assert.ok(html.indexOf('classic-verne-towle-ch21.js')<html.indexOf('classic-verne-towle-ch22.js'));
assert.ok(html.indexOf('classic-verne-towle-ch22.js')<html.indexOf('editorial-art.js'));
assert.ok(file.includes('1ae20fed64d05d867c7021cdfd1033a7fc71a879'),'exact upstream source blob is recorded');
const story={id:'around-the-world-in-eighty-days-towle',chapters:Array.from({length:21},()=>({paragraphs:[]})),terms:[],totalChapters:37,provenance:'Towle 1873',editorialStatus:'21 of 37'};
const context={window:{StoryLensEditorialStories:[story]},encodeURIComponent};
vm.runInNewContext(file,context,{filename:'classic-verne-towle-ch22.js',timeout:5000});
assert.equal(story.chapters.length,22);
const chapter=story.chapters[21];
assert.equal(chapter.paragraphs.length,31);
const english=chapter.paragraphs.map(p=>p.en).join(' ');
const words=(english.match(/[A-Za-z0-9]+(?:[’'-][A-Za-z0-9]+)*/g)||[]).length;
assert.ok(words>=2000,'Chapter XXII must remain substantial source text, not a synopsis: '+words);
assert.ok(english.startsWith('The Carnatic, setting sail from Hong Kong'));
assert.ok(english.endsWith('“Good! another Japanese embassy departing for Europe!”'));
assert.ok(chapter.paragraphs.every(p=>p.en.trim().length>0&&p.ar.trim().length>0&&/[\u0621-\u064A]/.test(p.ar)));
assert.equal(story.totalChapters,37);
assert.match(story.editorialStatus,/22 of 37/);
const chapterTerms=story.terms.filter(t=>t.note.includes('Chapter XXII:'));
assert.equal(chapterTerms.length,34);
for(const term of chapterTerms)assert.ok(english.toLowerCase().includes(term.term.toLowerCase()),'term absent from source: '+term.term);
const shell=read('lingua-shell.js'),css=read('lingua-shell.css'),backup=read('data-backup.js');
assert.ok(shell.includes("'yokohama-lantern':'Yokohama Lantern'"));
assert.ok(css.includes('body.theme-yokohama-lantern'));
assert.ok(css.includes('.lt-theme-yokohama-lantern .lt-theme-swatch'));
assert.ok(backup.includes("val==='yokohama-lantern'"));
const artContext={window:{}};
vm.runInNewContext(read('editorial-art.js'),artContext,{filename:'editorial-art.js',timeout:5000});
const art=artContext.window.StoryLensMakeEditorialArt([story]);
assert.ok(decodeURIComponent(art[story.id+'_21'].split(',')[1]).includes('YOKOHAMA LANTERN · XXII'));
assert.notEqual(art[story.id+'_21'],art[story.id+'_20'],'new chapter needs distinct offline art');
console.log('PASS Chapter XXII: '+words+' source words, '+chapter.paragraphs.length+' aligned bilingual passages, '+chapterTerms.length+' source-bound terms, distinct offline illustration/theme.');
