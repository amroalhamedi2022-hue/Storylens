'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),crypto=require('node:crypto'),path=require('node:path');
const root=path.resolve(__dirname,'..'),dir=path.join(root,'docs/literature/staging/kalila-arabic-wikisource');
const manifest=JSON.parse(fs.readFileSync(path.join(dir,'manifest.json'),'utf8'));
const original=fs.readFileSync(path.join(dir,'kalila.md'));
const provenance=JSON.parse(fs.readFileSync(path.join(dir,'upstream-catalog-record.json'),'utf8'));
const credits=fs.readFileSync(path.join(dir,'ATTRIBUTION_SOURCE.md'),'utf8');
assert.equal(manifest.literarySourceLanguage,'ar');
assert.equal(manifest.publishable,false);
assert.equal(manifest.sourceEdition.bytes,432293);
assert.equal(original.length,manifest.sourceEdition.bytes);
assert.equal(crypto.createHash('sha1').update('blob '+original.length+'\0').update(original).digest('hex'),manifest.sourceEdition.upstreamGitBlobSha,'Arabic source transcription altered');
assert.equal(manifest.sourceEdition.bookHeadingsH2,20);
const text=original.toString('utf8');
const headings=text.split('\n').filter(x=>x.startsWith('## '));
assert.equal(headings.length,20);
assert.match(text,/باب مقدمة الكتاب/);
assert.match(text,/باب الأسد والثور/);
assert.match(text,/باب ابن الملك وأصحابه/);
assert.match(text,/وقد جمعت لك في هذا الكتاب شمل بيان الأمور/);
assert.equal(provenance.id,'kalila');
assert.equal(provenance.words,45769);
assert.ok(provenance.sources.length>=19);
assert.ok(provenance.sources.every(url=>url.includes('ar.wikisource.org')&&url.includes('oldid=')));
assert.match(credits,/CC BY-SA 4\.0|النسبة — المشاركة بالمثل 4\.0/);
assert.equal(manifest.bilingual.allEnglishContextualTranslationPresent,false);
assert.equal(manifest.bilingual.alignableWith1819EnglishEdition,false);
assert.equal(manifest.rights.shareAlikeComplianceForReleaseReviewed,false);
assert.ok(!fs.readFileSync(path.join(root,'app/src/main/assets/index.html'),'utf8').includes(manifest.id),'Do not prematurely publish an unaligned Arabic book');
console.log('PASS: 432293-byte full Arabic Kalila candidate, exact source SHA, 20 section headings, 20 Wikisource revision links and honest translation/rights gates');
