'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const src=fs.readFileSync(path.join(root,'app/src/main/assets/freedict-en-ar.js'),'utf8');
const html=fs.readFileSync(path.join(root,'app/src/main/assets/index.html'),'utf8');
const context={window:{}};
vm.runInNewContext(src,context,{filename:'freedict-en-ar.js',timeout:5000});
const dict=context.window.FreeDictEnglishArabic;
assert.ok(dict,'FreeDict lookup object exists');
assert.ok(dict.size>=15000,'dictionary has substantial Arabic headword coverage');
const dog=dict.resolve('dog');
assert.ok(dog && /[\u0600-\u06ff]/.test(dog.literal),'English headword returns Arabic gloss');
assert.ok(Array.isArray(dog.meanings)&&dog.meanings.length>=1&&dog.meanings.length<=2,'dictionary returns up to two sourced senses');
assert.equal(dog.context,'','generic dictionary meanings must not masquerade as story-specific sense');
assert.ok(dict.resolve('dogs'),'regular plurals resolve');
assert.equal(dict.resolve('notarealenglishwordzzqx'),null,'unknown word receives no invented definition');
assert.match(dog.note,/FreeDict/,'source and context distinction remain visible');
assert.ok(html.includes('src="freedict-en-ar.js"'),'bundled asset loaded');
assert.ok(html.includes('window.FreeDictEnglishArabic.resolve(selected)'),'reader calls FreeDict after curated annotations');
const license=fs.readFileSync(path.join(root,'app/src/main/assets/LICENSE_FREEDICT.txt'),'utf8');
assert.match(license,/GPL|General Public License/i,'license and attribution shipped offline');
console.log(JSON.stringify({result:'PASS',headwords:dict.size,sampleDogGloss:dog.literal.substring(0,70),sourceBytes:Buffer.byteLength(src)}));
