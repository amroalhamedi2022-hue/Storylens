'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const assets=path.join(root,'app/src/main/assets');
const read=n=>fs.readFileSync(path.join(assets,n),'utf8');
const file=read('classic-verne-towle-ch23.js');
const html=read('index.html');
assert.ok(html.includes('src="classic-verne-towle-ch22.js"'));
assert.ok(html.includes('src="classic-verne-towle-ch23.js"'));
assert.ok(html.indexOf('classic-verne-towle-ch22.js')<html.indexOf('classic-verne-towle-ch23.js'));
assert.ok(html.indexOf('classic-verne-towle-ch23.js')<html.indexOf('editorial-art.js'));
assert.ok(file.includes('0757ba736579c0474a2e8e55b4dd4262a78da966'),'exact upstream source blob is recorded');
const story={id:'around-the-world-in-eighty-days-towle',chapters:Array.from({length:22},()=>({paragraphs:[]})),terms:[],totalChapters:37,provenance:'Towle 1873',editorialStatus:'22 of 37'};
const context={window:{StoryLensEditorialStories:[story]},encodeURIComponent};
vm.runInNewContext(file,context,{filename:'classic-verne-towle-ch23.js',timeout:5000});
assert.equal(story.chapters.length,23);
const chapter=story.chapters[22];
assert.equal(chapter.paragraphs.length,53);
const english=chapter.paragraphs.map(p=>p.en).join(' ');
assert.ok(english.includes('barrels, etc., was executed with wonderful precision.'),'English punctuation must match the verified source edition');
assert.ok(!english.includes('etc. ,'),'do not introduce a space before the source comma');
const words=(english.match(/[A-Za-z0-9]+(?:[’'-][A-Za-z0-9]+)*/g)||[]).length;
assert.ok(words>=1800,'Chapter XXIII must remain full source text, not a synopsis: '+words);
assert.ok(english.startsWith('The next morning poor, jaded, famished Passepartout'));
assert.ok(english.endsWith('stepped upon the American steamer.'));
assert.ok(chapter.paragraphs.every(p=>p.en.trim().length>0&&p.ar.trim().length>0&&/[\u0621-\u064A]/.test(p.ar)));
assert.equal(story.totalChapters,37);
assert.match(story.editorialStatus,/23 of 37/);
const chapterTerms=story.terms.filter(t=>t.note.includes('Chapter XXIII:'));
assert.equal(chapterTerms.length,35);
for(const term of chapterTerms)assert.ok(english.toLowerCase().includes(term.term.toLowerCase()),'term absent from source: '+term.term);
const shell=read('lingua-shell.js'),css=read('lingua-shell.css'),backup=read('data-backup.js');
assert.ok(shell.includes("'paper-lantern-circus':'Paper Lantern Circus'"));
assert.ok(css.includes('body.theme-paper-lantern-circus'));
assert.ok(css.includes('.lt-theme-paper-lantern-circus .lt-theme-swatch'));
assert.ok(backup.includes("val==='paper-lantern-circus'"));
const artContext={window:{}};
vm.runInNewContext(read('editorial-art.js'),artContext,{filename:'editorial-art.js',timeout:5000});
const art=artContext.window.StoryLensMakeEditorialArt([story]);
assert.ok(decodeURIComponent(art[story.id+'_22'].split(',')[1]).includes('PAPER LANTERN CIRCUS · XXIII'));
assert.notEqual(art[story.id+'_22'],art[story.id+'_21'],'new chapter needs distinct offline art');
console.log('PASS Chapter XXIII: '+words+' source words, '+chapter.paragraphs.length+' aligned bilingual passages, '+chapterTerms.length+' source-bound terms, distinct offline illustration/theme.');
