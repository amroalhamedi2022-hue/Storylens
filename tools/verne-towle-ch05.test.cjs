'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const assets=path.join(__dirname,'../app/src/main/assets');
const read=name=>fs.readFileSync(path.join(assets,name),'utf8');
const html=read('index.html');
assert.ok(html.indexOf('classic-verne-towle-ch04.js')<html.indexOf('classic-verne-towle-ch05.js'));
assert.ok(html.indexOf('classic-verne-towle-ch05.js')<html.indexOf('editorial-art.js'));
const story={id:'around-the-world-in-eighty-days-towle',genre:'historical',chapters:[{},{},{},{}],terms:[],totalChapters:37,provenance:''};
const sandbox={window:{StoryLensEditorialStories:[story]}};
vm.runInNewContext(read('classic-verne-towle-ch05.js'),sandbox,{filename:'classic-verne-towle-ch05.js'});
const chapter=story.chapters[4];
assert.equal(story.chapters.length,5);
assert.equal(chapter.paragraphs.length,14,'all prose and four telegram lines must be aligned');
assert.ok(chapter.paragraphs.every(p=>p.en.trim()&&p.ar.trim()),'no missing English or Arabic paragraph');
const english=chapter.paragraphs.map(p=>p.en).join(' ');
const wordCount=(english.match(/[\p{L}\p{N}’'-]+/gu)||[]).length;
assert.ok(wordCount>900,'chapter must be substantial, not a synopsis');
for(const phrase of ['lively sensation','crossing India in three days','five thousand pounds','warrant of arrest to Bombay','throw them off his track'])
 assert.ok(english.toLowerCase().includes(phrase.toLowerCase()),'missing source passage: '+phrase);
const addedTerms=story.terms.slice(-18);
assert.equal(addedTerms.length,18);
for(const entry of addedTerms)assert.ok(english.toLowerCase().includes(entry.term.toLowerCase()),'term not source-bound: '+entry.term);
assert.equal(story.totalChapters,37);
assert.match(story.editorialStatus,/5 of 37/);
vm.runInNewContext(read('editorial-art.js'),sandbox,{filename:'editorial-art.js'});
const art=sandbox.window.StoryLensMakeEditorialArt([story]);
assert.ok(art[story.id+'_4'].startsWith('data:image/svg+xml'));
assert.notEqual(art[story.id+'_4'],art[story.id+'_3'],'chapter V needs its own offline contextual illustration');
const shell=read('lingua-shell.js'),css=read('lingua-shell.css'),backup=read('data-backup.js');
assert.ok(shell.includes("'exchange-gazette'"));
assert.ok(shell.includes("'exchange-gazette':'Exchange Gazette'"));
assert.ok(css.includes('body.theme-exchange-gazette'));
assert.ok(backup.includes("'exchange-gazette'"),'Exchange Gazette must remain backup-allowlisted');
console.log('PASS Towle V: 14 aligned paragraphs, '+wordCount+' source words, 18 source-bound terms, distinct offline art and Exchange Gazette theme');
