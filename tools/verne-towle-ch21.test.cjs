'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const assets=path.join(root,'app/src/main/assets');
const read=n=>fs.readFileSync(path.join(assets,n),'utf8');
const file=read('classic-verne-towle-ch21.js');
const html=read('index.html');
assert.ok(html.includes('src="classic-verne-towle-ch20.js"'));
assert.ok(html.includes('src="classic-verne-towle-ch21.js"'));
assert.ok(html.indexOf('classic-verne-towle-ch20.js')<html.indexOf('classic-verne-towle-ch21.js'));
assert.ok(html.indexOf('classic-verne-towle-ch21.js')<html.indexOf('editorial-art.js'));
assert.ok(file.includes('47c6a1144e756752618e36c56f21832d1020f3fb'),'exact upstream source blob is recorded');
const story={id:'around-the-world-in-eighty-days-towle',chapters:Array.from({length:20},()=>({paragraphs:[]})),terms:[],totalChapters:37,provenance:'Towle 1873',editorialStatus:'20 of 37'};
const context={window:{StoryLensEditorialStories:[story]},encodeURIComponent};
vm.runInNewContext(file,context,{filename:'classic-verne-towle-ch21.js',timeout:5000});
assert.equal(story.chapters.length,21);
const chapter=story.chapters[20];
assert.equal(chapter.paragraphs.length,55);
const english=chapter.paragraphs.map(p=>p.en).join(' ');
const words=(english.match(/[A-Za-z0-9]+(?:[’'-][A-Za-z0-9]+)*/g)||[]).length;
assert.ok(words>=2500,'Chapter XXI must be substantial source text, not a synopsis: '+words);
assert.ok(english.startsWith('This voyage of eight hundred miles'));
assert.ok(english.endsWith('“Fire!” said Mr. Fogg. And the booming of the little cannon resounded in the air.'));
assert.ok(chapter.paragraphs.every(p=>p.en.trim().length>0&&p.ar.trim().length>0&&/[\u0621-\u064A]/.test(p.ar)));
assert.equal(story.totalChapters,37);
assert.match(story.editorialStatus,/21 of 37/);
const chapterTerms=story.terms.filter(t=>t.note.includes('Chapter XXI:'));
assert.equal(chapterTerms.length,33);
for(const term of chapterTerms)assert.ok(english.toLowerCase().includes(term.term.toLowerCase()),'term absent from source: '+term.term);
const shell=read('lingua-shell.js'),css=read('lingua-shell.css'),backup=read('data-backup.js');
assert.ok(shell.includes("'typhoon-signal':'Typhoon Signal'"));
assert.ok(css.includes('body.theme-typhoon-signal'));
assert.ok(css.includes('.lt-theme-typhoon-signal .lt-theme-swatch'));
assert.ok(backup.includes("val==='typhoon-signal'"));
const artContext={window:{}};
vm.runInNewContext(read('editorial-art.js'),artContext,{filename:'editorial-art.js',timeout:5000});
const art=artContext.window.StoryLensMakeEditorialArt([story]);
assert.ok(art[story.id+'_20'].includes('TYPHOON SIGNAL · XXI'));
assert.notEqual(art[story.id+'_20'],art[story.id+'_19'],'new chapter needs distinct offline art');
console.log('PASS Chapter XXI: '+words+' source words, '+chapter.paragraphs.length+' aligned bilingual passages, '+chapterTerms.length+' source-bound terms, distinct offline illustration/theme.');
