'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const assets=path.join(__dirname,'../app/src/main/assets'),read=n=>fs.readFileSync(path.join(assets,n),'utf8');
const html=read('index.html');
assert.ok(html.indexOf('classic-verne-towle-ch05.js')<html.indexOf('classic-verne-towle-ch06.js'));
assert.ok(html.indexOf('classic-verne-towle-ch06.js')<html.indexOf('editorial-art.js'));
const story={id:'around-the-world-in-eighty-days-towle',genre:'historical',chapters:[{},{},{},{},{}],terms:[],totalChapters:37,provenance:''};
const sandbox={window:{StoryLensEditorialStories:[story]}};
vm.runInNewContext(read('classic-verne-towle-ch06.js'),sandbox,{filename:'classic-verne-towle-ch06.js'});
const chapter=story.chapters[5],english=chapter.paragraphs.map(p=>p.en).join(' ');
assert.equal(story.chapters.length,6);
assert.equal(chapter.paragraphs.length,37);
assert.ok(chapter.paragraphs.every(p=>p.en.trim()&&p.ar.trim()));
const words=(english.match(/[\\p{L}\\p{N}’'-]+/gu)||[]).length;
assert.ok(words>1250,'full chapter VI required');
for(const phrase of ['fifty-five thousand pounds','four hours','eleven o’clock','Scotland Yard','Quite indispensable'])
 assert.ok(english.toLowerCase().includes(phrase.toLowerCase()),'missing original scene: '+phrase);
assert.equal(story.terms.length,17);
for(const term of story.terms)assert.ok(english.toLowerCase().includes(term.term.toLowerCase()),'not in source: '+term.term);
assert.equal(story.totalChapters,37);
assert.match(story.editorialStatus,/6 of 37/);
vm.runInNewContext(read('editorial-art.js'),sandbox,{filename:'editorial-art.js'});
const art=sandbox.window.StoryLensMakeEditorialArt([story]);
assert.ok(art[story.id+'_5'].startsWith('data:image/svg+xml'));
assert.notEqual(art[story.id+'_5'],art[story.id+'_4']);
const shell=read('lingua-shell.js'),css=read('lingua-shell.css'),backup=read('data-backup.js');
assert.ok(shell.includes("'suez-quays'"));
assert.ok(shell.includes("'suez-quays':'Suez Quays'"));
assert.ok(css.includes('body.theme-suez-quays'));
assert.ok(backup.includes("'suez-quays'].includes(val)"));
console.log('PASS Towle VI: 37 aligned paragraphs, '+words+' source words, 17 source terms, offline art and Suez Quays theme');
