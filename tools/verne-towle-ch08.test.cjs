'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const assets=path.join(__dirname,'../app/src/main/assets'),read=n=>fs.readFileSync(path.join(assets,n),'utf8');
const html=read('index.html');
assert.ok(html.indexOf('classic-verne-towle-ch07.js')<html.indexOf('classic-verne-towle-ch08.js'));
assert.ok(html.indexOf('classic-verne-towle-ch08.js')<html.indexOf('editorial-art.js'));
const story={id:'around-the-world-in-eighty-days-towle',genre:'historical',chapters:Array.from({length:7},()=>({})),terms:[],totalChapters:37,provenance:''};
const sandbox={window:{StoryLensEditorialStories:[story]}};
vm.runInNewContext(read('classic-verne-towle-ch08.js'),sandbox,{filename:'classic-verne-towle-ch08.js'});
const chapter=story.chapters[7],english=chapter.paragraphs.map(p=>p.en).join(' ');
const norm=s=>s.toLowerCase().replace(/[^\p{L}\p{N}]+/gu,' ').trim();
assert.equal(story.chapters.length,8);
assert.equal(chapter.paragraphs.length,59);
assert.ok(chapter.paragraphs.every(p=>p.en.trim()&&p.ar.trim()));
const words=(english.match(/[A-Za-z0-9]+(?:[’'-][A-Za-z0-9]+)*/g)||[]).length;
assert.ok(words>1000,'full Chapter VIII source required');
for(const phrase of ['Fix soon rejoined Passepartout','Père la Chaise','family watch','something else in the wind','well in advance of time','cogitating a project','rode out at full steam'])
 assert.ok(norm(english).includes(norm(phrase)),'missing original scene: '+phrase);
assert.equal(story.terms.length,26);
for(const term of story.terms)assert.ok(norm(english).includes(norm(term.term)),'term absent from source: '+term.term);
assert.equal(story.totalChapters,37);
assert.match(story.editorialStatus,/8 of 37/);
vm.runInNewContext(read('editorial-art.js'),sandbox,{filename:'editorial-art.js'});
const art=sandbox.window.StoryLensMakeEditorialArt([story]);
assert.ok(art[story.id+'_7'].startsWith('data:image/svg+xml'));
assert.notEqual(art[story.id+'_7'],art[story.id+'_6']);
assert.ok(decodeURIComponent(art[story.id+'_7']).includes('telegraph dispatch desk'));
const sh=read('lingua-shell.js'),backup=read('data-backup.js');
assert.ok(sh.includes("'red-sea-dispatch'"));
assert.ok(sh.includes("'red-sea-dispatch':'Red Sea Dispatch'"));
assert.ok(html.includes('body.theme-red-sea-dispatch'));
assert.ok(backup.includes("val==='red-sea-dispatch'"));
console.log('PASS Towle VIII: 59 aligned paragraphs, '+words+' English words, 26 source-bound terms, bespoke offline telegraph art and Red Sea Dispatch theme');
