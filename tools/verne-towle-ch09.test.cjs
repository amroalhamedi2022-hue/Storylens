'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const assets=path.join(__dirname,'../app/src/main/assets'),read=n=>fs.readFileSync(path.join(assets,n),'utf8');
const html=read('index.html');
assert.ok(html.indexOf('classic-verne-towle-ch08.js')<html.indexOf('classic-verne-towle-ch09.js'));
assert.ok(html.indexOf('classic-verne-towle-ch09.js')<html.indexOf('editorial-art.js'));
const story={id:'around-the-world-in-eighty-days-towle',genre:'historical',chapters:Array.from({length:8},()=>({})),terms:[],totalChapters:37,provenance:''};
const sandbox={window:{StoryLensEditorialStories:[story]}};
vm.runInNewContext(read('classic-verne-towle-ch09.js'),sandbox,{filename:'classic-verne-towle-ch09.js'});
const chapter=story.chapters[8],english=chapter.paragraphs.map(p=>p.en).join(' ');
const norm=s=>s.toLowerCase().replace(/[^\\p{L}\\p{N}]+/gu,' ').trim();
assert.equal(story.chapters.length,9);
assert.equal(chapter.paragraphs.length,30);
assert.ok(chapter.paragraphs.every(p=>p.en.trim()&&p.ar.trim()));
const words=(english.match(/[A-Za-z0-9]+(?:[’'-][A-Za-z0-9]+)*/g)||[]).length;
assert.ok(words>1700,'complete original Chapter IX required, got '+words);
for(const phrase of ['The distance between Suez and Aden','the straits of Bab-el-Mandeb','gain the worthy man','pale ale','Steamer Point','the Indian coast','column of gains'])
 assert.ok(norm(english).includes(norm(phrase)),'missing original scene: '+phrase);
assert.equal(story.terms.length,23);
for(const term of story.terms)assert.ok(norm(english).includes(norm(term.term)),'term absent from source: '+term.term);
assert.equal(story.totalChapters,37);
assert.match(story.editorialStatus,/9 of 37/);
vm.runInNewContext(read('editorial-art.js'),sandbox,{filename:'editorial-art.js'});
const art=sandbox.window.StoryLensMakeEditorialArt([story]);
assert.ok(art[story.id+'_8'].startsWith('data:image/svg+xml'));
assert.notEqual(art[story.id+'_8'],art[story.id+'_7']);
assert.ok(decodeURIComponent(art[story.id+'_8']).includes('Bombay'));
const shell=read('lingua-shell.js'),backup=read('data-backup.js');
assert.ok(shell.includes("'monsoon-meridian':'Monsoon Meridian'"));
assert.ok(backup.includes("'monsoon-meridian'"));
assert.ok(html.includes('body.theme-monsoon-meridian'));
console.log('PASS Towle IX: 30 aligned paragraphs, '+words+' English words, 23 source-bound terms, bespoke offline Indian Ocean art and Monsoon Meridian theme');
