'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const assets=path.join(root,'app/src/main/assets');
const read=n=>fs.readFileSync(path.join(assets,n),'utf8');
const html=read('index.html');
const c19=read('classic-verne-towle-ch19.js');
const c20=read('classic-verne-towle-ch20.js');
assert.ok(html.includes('src="classic-verne-towle-ch19.js"')&&html.includes('src="classic-verne-towle-ch20.js"'));
assert.ok(html.indexOf('classic-verne-towle-ch19.js')<html.indexOf('classic-verne-towle-ch20.js'));
assert.ok(html.indexOf('classic-verne-towle-ch20.js')<html.indexOf('editorial-art.js'));
assert.ok(c20.includes('844ca4176ab3330e01b2745b68a51c6737d66a94'),'exact Standard Ebooks source blob is recorded');
const story={id:'around-the-world-in-eighty-days-towle',chapters:Array.from({length:18},()=>({paragraphs:[]})),terms:[],totalChapters:37,provenance:'Towle 1873',editorialStatus:'18 of 37'};
const box={window:{StoryLensEditorialStories:[story]},encodeURIComponent};
vm.runInNewContext(c19,box,{filename:'classic-verne-towle-ch19.js',timeout:5000});
vm.runInNewContext(c20,box,{filename:'classic-verne-towle-ch20.js',timeout:5000});
assert.equal(story.chapters.length,20);
const chapter=story.chapters[19],english=chapter.paragraphs.map(p=>p.en).join(' ');
const norm=s=>s.toLowerCase().replace(/\u2060/g,'').replace(/[^a-z0-9]+/g,' ').replace(/\s+/g,' ').trim();
const words=(english.match(/[A-Za-z0-9]+(?:[’'-][A-Za-z0-9]+)*/g)||[]).length;
assert.equal(chapter.paragraphs.length,72);
assert.ok(words>=1700,'Chapter XX must be substantial source text, not a synopsis: '+words);
assert.ok(chapter.paragraphs.every(p=>p.en.trim().length>0&&p.ar.trim().length>0&&/[\u0621-\u064A]/.test(p.ar)));
for(const phrase of ['unconscious of the danger','characteristic serenity','the Carnatic had sailed the evening before','charter a vessel','pilot-boat','mortal suspense','currents run northward','master of the Tankadere','stupefying influence of the opium','bounded briskly forward over the waves'])
 assert.ok(norm(english).includes(norm(phrase)),'missing source phrase: '+phrase);
assert.equal(story.terms.length,67,'chapter XIX terms plus Chapter XX terms');
for(const term of story.terms.slice(-33))assert.ok(norm(english).includes(norm(term.term)),'context term absent from source: '+term.term);
assert.match(chapter.title,/Fix comes face to face/i);
assert.match(story.editorialStatus,/20 of 37/);
vm.runInNewContext(read('editorial-art.js'),box,{filename:'editorial-art.js',timeout:5000});
const scenes=box.window.StoryLensMakeEditorialArt([story]);
const svg=decodeURIComponent(scenes[story.id+'_19']);
assert.ok(svg.includes('<svg')&&svg.includes('TANKADERE · SHANGHAI · XX'));
assert.notEqual(scenes[story.id+'_19'],scenes[story.id+'_18'],'each chapter has a distinct local scene');
const shell=read('lingua-shell.js'),css=read('lingua-shell.css'),backup=read('data-backup.js');
assert.ok(shell.includes("'shanghai-wind-ledger':'Shanghai Wind Ledger'"));
assert.ok(css.includes('body.theme-shanghai-wind-ledger')&&css.includes('.lt-theme-shanghai-wind-ledger .lt-theme-swatch'));
assert.ok(css.includes('@media(prefers-reduced-motion:reduce){.theme-shanghai-wind-ledger'));
assert.ok(backup.includes("'shanghai-wind-ledger'"));
console.log('PASS Towle XX: '+words+' source-transcribed English words, 72 aligned Arabic draft paragraphs, 33 source-bound terms, unique offline SVG/theme/backup.');
