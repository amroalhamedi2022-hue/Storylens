'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const assets=path.join(root,'app/src/main/assets');
const read=n=>fs.readFileSync(path.join(assets,n),'utf8');
const source=read('classic-verne-towle-ch26.js');
const html=read('index.html');
assert.ok(html.includes('src="classic-verne-towle-ch25.js"')&&html.includes('src="classic-verne-towle-ch26.js"'));
assert.ok(html.indexOf('classic-verne-towle-ch25.js')<html.indexOf('classic-verne-towle-ch26.js'));
assert.ok(html.indexOf('classic-verne-towle-ch26.js')<html.indexOf('editorial-art.js'));
assert.ok(source.includes('chapter-26.xhtml')&&source.includes('d81f9235390ec9dac8c7e27ed08ba76ecf55a709'));
const story={id:'around-the-world-in-eighty-days-towle',chapters:Array.from({length:25},()=>({paragraphs:[]})),terms:[],totalChapters:37,provenance:'Towle 1873',editorialStatus:'25 of 37'};
vm.runInNewContext(source,{window:{StoryLensEditorialStories:[story]}},{filename:'classic-verne-towle-ch26.js',timeout:5000});
assert.equal(story.chapters.length,26);
const chapter=story.chapters[25];
assert.equal(chapter.paragraphs.length,25);
assert.equal(chapter.paragraphs.map(p=>p.en).join(' ').split(/\s+/).length,1605);
assert.ok(chapter.paragraphs.every(p=>typeof p.ar==='string'&&p.ar.trim().length>20));
assert.equal(story.terms.length,36);
const body=chapter.paragraphs.map(p=>p.en).join(' ').toLowerCase();
for(const t of story.terms) assert.ok(body.includes(t.term.toLowerCase()),'glossary surface absent from source: '+t.term);
assert.equal(story.totalChapters,37);
assert.ok(story.editorialStatus.includes('26 of 37'));
const artSandbox={window:{}};
vm.runInNewContext(read('editorial-art.js'),artSandbox,{filename:'editorial-art.js',timeout:5000});
const art=artSandbox.window.StoryLensMakeEditorialArt([story]);
assert.ok(art['around-the-world-in-eighty-days-towle_25']);
assert.notEqual(art['around-the-world-in-eighty-days-towle_24'],art['around-the-world-in-eighty-days-towle_25'],'new chapter scene must be original and distinct');
assert.ok(art['around-the-world-in-eighty-days-towle_25'].includes('PRAIRIE%20SIGNAL'));
console.log('PASS Towle XXVI: 25 aligned bilingual paragraphs, 1,605 source words, 36 source-bound glossary entries, source pin, navigation order and unique offline SVG.');
