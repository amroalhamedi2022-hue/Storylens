#!/usr/bin/env node
/* Multi-engine authoring brief exporter. NO image generation / NO external APIs.
 * Exact source paragraph anchors and character appearance supplied by
 * tools/story_art_pilot.cjs; human review remains mandatory.
 */
'use strict';
const fs=require('node:fs'),path=require('node:path'),os=require('node:os');
const {run:verifiedQueue}=require('./story_art_pilot.cjs');
const DEFAULT=path.join(os.tmpdir(),'lingua-story-art-briefs');
function serialise(queue){
 if(!queue||queue.releaseApproved!==false||queue.queueCount!==5||
    !Array.isArray(queue.queue)||queue.queue.length!==5||
    queue.queue.some(s=>s.editoriallyApproved||s.status!=='PROMPT_READY_NOT_GENERATED'))
  throw Error('Refusing to export a non-verified or ambiguously approved scene queue');
 const make=(target,custom)=>{
  const header=[
   'Lingua Tales — '+target+' | Scene-specific authoring prompts',
   'Generated from actual, verified bilingual novel paragraphs.',
   'ALL images are MODERN AI ART, NEVER historical originals.',
   'Five candidates. ZERO approved pictures. Human passage/visual/rights review mandatory.',
   'Do not fabricate events not in each cited paragraph.',
   ''
  ];
  for(const scene of queue.queue){
   const source=scene.chapterOneBased+' / paragraph '+(scene.afterParagraph+1);
   header.push('=== '+scene.sceneId+' | chapter '+source+' ===');
   header.push('Source (original text) — verified anchor: '+scene.sourceExcerpt);
   header.push('Original paragraph SHA256: '+scene.sourceParagraphSha256);
   header.push('English alt: '+scene.altEn);
   header.push('Arabic alt: '+scene.altAr);
   header.push(custom(scene.prompt));
   header.push('');
  }
  return header.join('\n')+'\n';
 };
 const prompt=s=>s.replace(/\s+/g,' ').trim();
 const files={
  'source-verified-queue.json':JSON.stringify(queue,null,2)+'\n',
  'midjourney-manual.txt':make('Midjourney — MANUAL only',s=>prompt(s)+' --ar 3:2'),
  'canva-image-prompt.txt':make('Canva image generator — MANUAL or connected',s=>prompt(s)),
  'chatgpt-image-prompt.txt':make('ChatGPT Images — MANUAL preview',s=>prompt(s)),
  'REVIEW-FIRST.txt':[
   'Use exactly ONE prompt/scene per image; never generate a collage or infographic.',
   'Keep character likeness + period style consistent using independently rights-approved reference images.',
   'Do NOT invent source artist/date or present AI imagery as archival scans.',
   'Check image against exact source excerpt, full paragraph, named characters, 1872 period, and visual continuity.',
   'Save a real image binary + SHA256 + editor/owner/territory rights before separate approval and packaging.',
   'No actual images are generated by this exporter; no API calls, no money charged.',
   ''
  ].join('\n')
 };
 return files;
}
function main(argv){
 let out=DEFAULT;
 for(let i=0;i<argv.length;i++){
  if(argv[i]==='--output-dir')out=path.resolve(argv[++i]||'');
  else throw Error('Unsupported option '+argv[i]);
 }
 const queue=verifiedQueue(['--check']);
 const files=serialise(queue);
 fs.mkdirSync(out,{recursive:true});
 for(const [name,content] of Object.entries(files)){
  const filename=path.join(out,name);
  if(fs.existsSync(filename)&&fs.readFileSync(filename,'utf8')!==content)
   throw Error('Refuse overwrite of different exported prompt '+filename);
  fs.writeFileSync(filename,content,'utf8');
 }
 console.log('PASS exported '+queue.queue.length+' real scene briefs to OpenAI, Canva and manual Midjourney; 0 image/API calls');
 return files;
}
if(require.main===module)try{main(process.argv.slice(2));}catch(e){console.error('FAIL '+e.message);process.exitCode=1;}
module.exports={serialise,main};
