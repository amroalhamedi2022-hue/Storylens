#!/usr/bin/env python3
"""Materialise genuine source-anchored chapter image candidate maps for 5 classics.

All selected images are ALREADY locally archived. No invented art, no network,
no source text changes, no reader/UI changes, no rights clearance by AI.
Each map contains one distinct checksum-verified ORIGINAL edition image for
a chapter when the edition really provides an image within that chapter.
Requires bs4 only for exact source-heading extraction. Run --verify to compare
generated bytes against existing checked-in maps; --write to create them.
"""
from __future__ import annotations

import argparse
import hashlib
import html
import json
import re
from pathlib import Path
import sys

from bs4 import BeautifulSoup

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / "docs/literature/staging/illustrated-five-20261105"
CURATED_SCENES = BASE / "curated-original-scene-evidence.json"
CONFIG = {
    "treasure-island": {"chapters": 34, "heading": "roman"},
    "kidnapped": {"chapters": 30, "heading": "chapter_with_title"},
    "the-black-arrow": {"chapters": 32, "heading": "book_chapter_title"},
    "the-last-of-the-mohicans": {"chapters": 33, "heading": "chapter"},
    "the-gilded-age": {"chapters": 63, "heading": "chapter"},
}

ROMAN_VALUES = {"I": 1, "V": 5, "X": 10, "L": 50, "C": 100, "D": 500, "M": 1000}
ROMAN_RE = re.compile(r"^[IVXLCDM]+$")
CHAPTER_RE = re.compile(r"^CHAPTER\s+([IVXLCDM]+)\b\.?\s*(.*)$", re.IGNORECASE)
ROMAN_TITLE_RE = re.compile(r"^([IVXLCDM]+)\s+(.+)$")
SCENE_EXCLUSION = re.compile(
    r"^(?:decorative|frontispiece|cover(?:[.\s]|$)|end.?paper|title.?page|"
    r"chapter\s+[ivxlcdm]+\b|list of|contents|illustrations?\s+list|"
    r"[ivxlcdm]{1,4}$|[p0-9_./-]+\.(?:jpe?g|png)|[0-9]{2,}[a-z]?$)",
    re.IGNORECASE,
)


def roman_to_int(text: str) -> int:
    if not ROMAN_RE.fullmatch(text):
        raise ValueError("Non-Roman chapter heading " + text)
    total, last = 0, 0
    for ch in reversed(text):
        v = ROMAN_VALUES[ch]
        total += -v if v < last else v
        last = max(last, v)
    if total < 1 or total > 100:
        raise ValueError("Invalid numbered chapter " + text)
    return total


def original_chapters(slug: str, raw: bytes) -> list[dict]:
    soup = BeautifulSoup(raw, "html.parser")
    heads = [" ".join(h.get_text(" ", strip=True).split())
             for h in soup.find_all(["h1", "h2", "h3", "h4", "h5", "h6"])]
    mode = CONFIG[slug]["heading"]
    rows = []
    book = 0
    for i, heading in enumerate(heads):
        if mode == "roman":
            match = ROMAN_TITLE_RE.match(heading)
            if match:
                num = roman_to_int(match.group(1))
                if num <= 34:
                    rows.append({"chapterOneBased": num, "titleEn": heading,
                                 "_sourceHeading": heading})
        elif mode == "chapter_with_title":
            match = CHAPTER_RE.match(heading)
            if match and match.group(2).strip():
                rows.append({"chapterOneBased": roman_to_int(match.group(1).upper()),
                             "titleEn": heading, "_sourceHeading": heading})
        elif mode == "book_chapter_title":
            if re.fullmatch(r"BOOK\s+[IVXLC]+", heading):
                book += 1
            match = CHAPTER_RE.match(heading)
            if match and book > 0 and not match.group(2).strip():
                if i + 1 >= len(heads):
                    raise ValueError("Black Arrow chapter heading has no title")
                next_title = heads[i + 1]
                if not next_title or next_title.startswith("CHAPTER "):
                    raise ValueError("Black Arrow chapter title is invalid")
                rows.append({"chapterOneBased": len(rows) + 1,
                             "bookOneBased": book,
                             "chapterWithinBook": roman_to_int(match.group(1).upper()),
                             "titleEn": next_title, "_sourceHeading": next_title})
        elif mode == "chapter":
            match = CHAPTER_RE.match(heading)
            if match and not match.group(2).strip():
                rows.append({"chapterOneBased": roman_to_int(match.group(1).upper()),
                             "titleEn": heading, "_sourceHeading": heading})
    target = CONFIG[slug]["chapters"]
    indices = [r["chapterOneBased"] for r in rows]
    if len(rows) != target or indices != list(range(1, target + 1)):
        raise ValueError(f"{slug}: chapter sequence not exactly 1..{target}: {indices!r}")
    if slug == "the-black-arrow":
        books = [r["bookOneBased"] for r in rows]
        if sorted(set(books)) != [1, 2, 3, 4, 5]:
            raise ValueError("Black Arrow Book I–V context not intact")
        # 7+5+6+6+8, excluding separate prologue.
        if [books.count(i) for i in range(1, 6)] != [7, 5, 6, 6, 8]:
            raise ValueError("Black Arrow narrative section count changed")
    return rows


def scene_caption(row: dict) -> str | None:
    raw = " ".join(str(row.get("captionOrAltFromOriginal", "")).split())
    if not raw or len(raw) < 16 or SCENE_EXCLUSION.match(raw):
        return None
    return raw


def scene_score(row: dict) -> tuple[int, int, int]:
    alt = scene_caption(row)
    return (
        100 if alt else 0,
        int(row.get("sourceWidth", 0)) * int(row.get("sourceHeight", 0)),
        int(row.get("webpBytes", 0)),
    )


def eligible(row: dict) -> bool:
    if row.get("literaryArtwork") is not True:
        return False
    if int(row.get("width", 0)) < 240 or int(row.get("height", 0)) < 200:
        return False
    if "decorative" in str(row.get("captionOrAltFromOriginal", "")).lower():
        return False
    if int(row.get("webpBytes", 0)) < 10000:
        return False
    return True


def make_map(slug: str) -> dict:
    folder = BASE / slug
    manifest = json.loads((folder / "manifest.json").read_text(encoding="utf-8"))
    original_bytes = (folder / "original-full-edition.html").read_bytes()
    expected = manifest["source"]["sha256"]
    if hashlib.sha256(original_bytes).hexdigest() != expected:
        raise ValueError("Source HTML SHA256 mismatch for " + slug)
    chapter_rows = original_chapters(slug, original_bytes)
    by_heading = {row["_sourceHeading"]: row for row in chapter_rows}
    picks: dict[int, dict] = {}
    for art in manifest["art"]:
        source_heading = " ".join(str(art.get("nearestPriorHeading", "")).split())
        chapter = by_heading.get(source_heading)
        if chapter is None or not eligible(art):
            continue
        idx = chapter["chapterOneBased"]
        image_path = folder / art["localPath"]
        if not image_path.is_file():
            raise ValueError("Missing already-archived original plate: " + str(image_path))
        raw = image_path.read_bytes()
        if hashlib.sha256(raw).hexdigest() != art["webpSha256"]:
            raise ValueError("Already-archived original plate corrupted: " + str(image_path))
        if len(raw) != int(art["webpBytes"]) or raw[:4] != b"RIFF" or raw[8:12] != b"WEBP":
            raise ValueError("Already-archived image not a correctly sized WebP")
        current = picks.get(idx)
        if current is None or scene_score(art) > scene_score(current):
            picks[idx] = art

    used = set()
    mapped = []
    for row in chapter_rows:
        heading = row.pop("_sourceHeading")
        idx = row["chapterOneBased"]
        art = picks.get(idx)
        row["titleAr"] = ""  # needs editorial translation; never invent titles
        if art is None:
            row["primaryImage"] = None
            row["imageStatus"] = "NO_SOURCE_MATCHED_LOCAL_PRIMARY"
            mapped.append(row)
            continue
        image_path = str((folder / art["localPath"]).relative_to(ROOT)).replace("\\", "/")
        if image_path in used:
            raise ValueError("Chapter images must be distinct; repeat " + image_path)
        used.add(image_path)
        original_caption = scene_caption(art)
        row["primaryImage"] = {
            "imagePath": image_path,
            "sha256": art["webpSha256"],
            "originalSourceSha256": art["sourceSha256"],
            "sourceUrl": art["originalSourceUrl"],
            "sourceEdition": manifest["illustratedEditionCredit"],
            "sourceBookEditionURL": manifest["source"]["originalFullHTMLUrl"],
            "sourceChapterHeading": heading,
            "sourceOriginalImageOrdinal": art["imageOrdinalInExactSourceDOM"],
            "sceneAnchor": (
                "Chapter-local original illustration, heading: " + heading
                + (("; original illustration caption: " + original_caption) if original_caption else "")
                + (("; preceding prose: " + art["priorProsePreview"][:140])
                   if art.get("priorProsePreview") else "")
            ),
            "sceneVerificationStatus": "SOURCE_DOM_CHAPTER_MATCHED__IMAGE_SUBJECT_REQUIRES_HUMAN_REVIEW",
            "originalCaption": art.get("captionOrAltFromOriginal", ""),
            "credit": manifest["illustratedEditionCredit"],
            "license": art.get("illustrationRights", "PENDING_PER_FILE_RIGHTS_REVIEW"),
            "rightsStatus": "PENDING_PER_SCAN_AND_TERRITORY_REVIEW",
            "altEn": (original_caption or
                      f"Original edition artwork within chapter {idx}; exact pictured subject not yet visually verified."),
            "altAr": f"رسم من الطبعة التاريخية للفصل {idx}؛ تفاصيل المشهد تحتاج تحققًا بصريًا قبل النشر.",
            "editoriallyApproved": False,
        }
        row["imageStatus"] = "SOURCE_ANCHORED_LOCAL_CANDIDATE_NOT_APPROVED"
        mapped.append(row)

    target = CONFIG[slug]["chapters"]
    book = {
        "schemaVersion": 1,
        "bookId": slug,
        "source": manifest["source"]["originalFullHTMLUrl"],
        "sourceTextSha256": expected,
        "chapterCount": target,
        "localCandidateChapters": len(picks),
        "missingCandidateChapters": target - len(picks),
        "readyForUICards": 0,
        "releaseApproved": False,
        "rightsStatus": "PENDING_INDIVIDUAL_ARTWORK_AND_TERRITORIAL_CLEARANCE",
        "mappingMethod": "EXACT_AUTHENTIC_SOURCE_HEADING_AND_ORDERED_INLINE_IMAGE_TAG_PROVENANCE",
        "editorialCaution": (
            "Candidate images are real local, SHA-verified and originally positioned under "
            "these chapters, but exact depicted scene, individual scan rights, book-wide "
            "translation and chapter thumbnail visual/editorial review are NOT cleared. "
            "Do NOT publish into app until verified."
        ),
        "sourceArchiveManifest": str((folder / "manifest.json").relative_to(ROOT)),
        "chapters": mapped,
    }
    # Keep source-verified scenes overlaid *after* automatic image selection.
    # Otherwise the nightly mapping job deletes them silently on every run.
    return apply_curated_scenes(slug, book, original_bytes, manifest)


def apply_curated_scenes(slug: str, book: dict, original_bytes: bytes,
                         manifest: dict, evidence: dict | None = None) -> dict:
    """Fail-closed preservation of genuinely source-proven art, never auto-release.

    The curated file is a separate, durable input: generated maps must not be
    their own only source of truth. Bad proofs fail CI rather than resetting to
    blank cards or replacing a human-selected original with stock art.
    """
    if evidence is None:
        evidence = json.loads(CURATED_SCENES.read_text(encoding="utf-8"))
    if (evidence.get("schemaVersion") != 1
            or evidence.get("releaseApproved") is not False
            or not isinstance(evidence.get("chapterScenes"), list)):
        raise ValueError("Curated source-scene evidence schema / release hold invalid")

    seen_chapters = set()
    for record in evidence["chapterScenes"]:
        key = (record.get("bookId"), record.get("chapterOneBased"))
        if key in seen_chapters:
            raise ValueError("Duplicate curated chapter scene: " + str(key))
        seen_chapters.add(key)
        if key[0] != slug:
            continue
        # Every accepted exception must have a dedicated original-source test
        # and a previously verified historical image. Extend this allow-list
        # only alongside specific evidence and negative regression tests.
        if key != ("the-gilded-age", 30):
            raise ValueError("Unreviewed curated exception: " + str(key))
        photo = record.get("primaryImage")
        if not isinstance(photo, dict):
            raise ValueError("Curated image evidence missing")
        art = next((a for a in manifest["art"] if
                    a.get("imageOrdinalInExactSourceDOM") == photo.get("sourceOriginalImageOrdinal")), None)
        if art is None:
            raise ValueError("Unknown historical image ordinal")
        row = book["chapters"][29]
        expected_path = str((BASE / slug / art["localPath"]).relative_to(ROOT))
        if (row["chapterOneBased"] != 30 or row["titleEn"] != "CHAPTER XXX."
                or art.get("nearestPriorHeading") != row["titleEn"]
                or art.get("originalRelativeImageSource") != "images/p277.jpg"
                or photo.get("sourceChapterHeading") != row["titleEn"]
                or photo.get("imagePath") != expected_path
                or photo.get("sha256") != art.get("webpSha256")
                or photo.get("originalSourceSha256") != art.get("sourceSha256")
                or photo.get("sourceUrl") != art.get("originalSourceUrl")
                or photo.get("sourceURL") != art.get("originalSourceUrl")
                or photo.get("sourceOriginalImageOrdinal") != 109
                or photo.get("sourceBookEditionURL") != manifest["source"]["originalFullHTMLUrl"]
                or photo.get("sourcePassage") != photo.get("sceneAnchor")
                or not isinstance(photo.get("sourcePassage"), str)
                or len(photo["sourcePassage"]) < 60
                or photo.get("editoriallyApproved") is not False
                or photo.get("publicationStatus") != "STAGING_ONLY_NOT_PUBLISHED"
                or photo.get("rightsStatus") != "PENDING_PER_SCAN_AND_TERRITORY_REVIEW"
                or photo.get("nonAIArt") is not True
                or photo.get("originalSourceImageEmbeddedWithinChapter") is not True
                or "HUMAN_SCENE_AND_RIGHTS_PENDING" not in str(photo.get("sceneVerificationStatus", ""))
                or not isinstance(photo.get("altAr"), str) or not photo["altAr"].strip()
                or not isinstance(photo.get("altEn"), str) or not photo["altEn"].strip()
                or record.get("imageStatus") != "ORIGINAL_BOOK_CH30_RAIL_TRAVEL_IMAGE_CANDIDATE_UNAPPROVED"):
            raise ValueError("Curated image not authenticated against original book metadata")
        raw_image = (ROOT / expected_path).read_bytes()
        if (len(raw_image) != art["webpBytes"]
                or raw_image[:4] != b"RIFF" or raw_image[8:12] != b"WEBP"
                or hashlib.sha256(raw_image).hexdigest() != art["webpSha256"]):
            raise ValueError("Curated original historical image corrupted")
        # The literal quoted scene and image filename must both occur inside
        # Chapter XXX rather than merely elsewhere in the same full book.
        raw_html = original_bytes.decode("utf-8")
        image_at = raw_html.find(art["originalRelativeImageSource"])
        chapter_at = raw_html.rfind("CHAPTER XXX.", 0, image_at)
        next_at = raw_html.find("CHAPTER XXXI.", chapter_at + 1)
        if (raw_html.count(art["originalRelativeImageSource"]) != 1
                or image_at < 0 or chapter_at < 0 or next_at < 0
                or not chapter_at < image_at < next_at):
            raise ValueError("Curated image not situated inside original source chapter")
        original_chapter_text = " ".join(
            html.unescape(re.sub(r"<[^>]+>", " ", raw_html[chapter_at:next_at])).split()
        )
        if photo["sourcePassage"] not in original_chapter_text:
            raise ValueError("Curated scene quotation not literal original Chapter XXX prose")
        if any(c["chapterOneBased"] != 30 and c["primaryImage"] and
               (c["primaryImage"]["imagePath"] == photo["imagePath"] or
                c["primaryImage"]["sha256"] == photo["sha256"])
               for c in book["chapters"]):
            raise ValueError("Curated image already assigned to another chapter")
        row["primaryImage"] = dict(photo)
        row["imageStatus"] = record["imageStatus"]

    book["localCandidateChapters"] = sum(bool(c["primaryImage"]) for c in book["chapters"])
    book["missingCandidateChapters"] = book["chapterCount"] - book["localCandidateChapters"]
    # Do not change book or individual-image release flags based on curation.
    if book["releaseApproved"] is not False or book["readyForUICards"] != 0:
        raise ValueError("Original chapter scene was incorrectly released")
    return book


def main() -> None:
    arg = argparse.ArgumentParser()
    arg.add_argument("--write", action="store_true")
    arg.add_argument("--verify", action="store_true")
    opts = arg.parse_args()
    if not opts.write and not opts.verify:
        arg.error("use --write or --verify")
    total = 0
    for slug in CONFIG:
        book = make_map(slug)
        serialized = json.dumps(book, ensure_ascii=False, indent=2) + "\n"
        target = BASE / slug / "chapter-image-map.json"
        if opts.verify and target.exists() and target.read_text(encoding="utf-8") != serialized:
            raise ValueError("Chapter map is stale or altered: " + str(target))
        if opts.write:
            if not target.exists() or target.read_text(encoding="utf-8") != serialized:
                target.write_text(serialized, encoding="utf-8")
        total += book["localCandidateChapters"]
        print(f"{slug}: {book['localCandidateChapters']}/{book['chapterCount']} "
              "source-anchored, SHA256-verified chapter image candidates; 0 release-approved", flush=True)
    print(f"SUCCESS: {total} unique chapter-primary historic candidate mappings; "
          "0 new image binaries, 0 release-approved cards, no changes to app", flush=True)


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:
        print("Historic chapter image mapping FAILED, no invented fallback: " + str(exc), file=sys.stderr)
        raise SystemExit(1)
