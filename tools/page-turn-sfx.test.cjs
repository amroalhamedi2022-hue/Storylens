'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const src=fs.readFileSync('app/src/main/assets/reader-experience.js','utf8');
const from=src.indexOf('let ltLastPaperSfxAt=-Infinity;');
const to=src.indexOf("function move(delta,source='control'){",from);
assert.ok(from>0&&to>from,'page sound helper located in production reader');
const source=src.slice(from,to)+'\nglobalThis.play=ltPlayPageTurnSfx;';
let now=1000,enabled=false,calls=[];
let reject=false;
const player={prefs:()=>({sfxEnabled:enabled}),playSfx(id){calls.push(id);return reject?Promise.reject(Error('codec')):Promise.resolve(true)}};
