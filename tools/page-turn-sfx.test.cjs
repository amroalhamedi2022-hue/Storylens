assert.equal(env.play(),false,'missing player never breaks offline reading');
assert.match(src,/current\+=delta;ltPlayPageTurnSfx\(\);renderPage/,'sound occurs at completed page turn');
assert.match(src,/if\(state\.chapter<state\.story\.chapters\.length-1\)\{ltPlayPageTurnSfx\(\);nextChapter\(\);\}/,'cross-chapter forward turn sounds at landing');
console.log('PASS: opt-in licensed page turn sound tied to completed navigation only');
