'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const assets=path.join(__dirname,'../app/src/main/assets'),read=n=>fs.readFileSync(path.join(assets,n),'utf8');
const html=read('index.html');
assert.ok(html.indexOf('classic-verne-towle-ch12.js')<html.indexOf('classic-verne-towle-ch13.js'));
assert.ok(html.indexOf('classic-verne-towle-ch13.js')<html.indexOf('editorial-art.js'));
const story={id:'around-the-world-in-eighty-days-towle',genre:'historical',chapters:Array.from({length:12},()=>({})),terms:[],totalChapters:37,provenance:''};
const box={window:{StoryLensEditorialStories:[story]}};
vm.runInNewContext(read('classic-verne-towle-ch13.js'),box,{filename:'classic-verne-towle-ch13.js'});
const ch=story.chapters[12],english=ch.paragraphs.map(p=>p.en).join(' '),norm=s=>s.toLowerCase().replace(/\u2060/g,'').replace(/[^a-z0-9]+/g,' ').replace(/\s+/g,' ').trim();
assert.equal(story.chapters.length,13);
assert.equal(ch.paragraphs.length,48);
assert.ok(ch.paragraphs.every(p=>p.en.trim()&&p.ar.trim()));
assert.ok(ch.paragraphs.every(p=>!p.ar.includes('الفقراوات')),'historical fakir term should not be mistranslated as poor women');
assert.ok(ch.paragraphs.some(p=>p.ar.includes('المتنسكون')),'Arabic companion draft should name the ascetics clearly');
const words=(english.match(/[A-Za-z0-9]+(?:[’'-][A-Za-z0-9]+)*/g)||[]).length;
assert.ok(words>2000,'Chapter XIII too short: '+words);
for(const phrase of ['bold one','enthusiastic ally','icy exterior','wealthy Bombay merchant','against her will','funeral pyre','make a reconnaissance','naked sabres','roundabout way','common prudence','without betraying any emotion','at the last moment','struck him like a flash','suppleness of a serpent','hour of the sacrifice','prostrated themselves','ghostly appearance','happy audacity','apprised them','beyond the reach of the bullets and arrows'])assert.ok(norm(english).includes(norm(phrase)),'missing source phrase: '+phrase);
assert.equal(story.terms.length,34);
for(const term of story.terms)assert.ok(norm(english).includes(norm(term.term)),'term absent from source: '+term.term);
assert.match(story.editorialStatus,/13 of 37/);
vm.runInNewContext(read('editorial-art.js'),box,{filename:'editorial-art.js'});
const art=box.window.StoryLensMakeEditorialArt([story]);
assert.ok(decodeURIComponent(art[story.id+'_12']).includes('DAWN ESCAPE'));
assert.notEqual(art[story.id+'_12'],art[story.id+'_11']);
assert.ok(read('lingua-shell.js').includes("'dawn-escape':'Dawn Escape'"));
assert.ok(read('data-backup.js').includes("val==='dawn-escape'"));
assert.ok(read('lingua-shell.css').includes('body.theme-dawn-escape'));
console.log('PASS Towle XIII: 48 aligned bilingual passages, '+words+' English words, 34 source-bound terms, distinct offline rescue scene and Dawn Escape theme');
